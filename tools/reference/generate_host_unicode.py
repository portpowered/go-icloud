"""Derive hostname lowercase and sigma context tables from pinned Unicode15.

Python's actual lower operation defines the effective context classification:
an ignorable character preserves both surrounding sigma context probes; a
cased character keeps sigma nonfinal even without a following cased letter.
"""

import argparse
import hashlib
import json
import subprocess
import unicodedata
from pathlib import Path


def ranges(values):
    result = []
    for value in values:
        if result and result[-1][1] + 1 == value:
            result[-1][1] = value
        else:
            result.append([value, value])
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    if unicodedata.unidata_version != "15.0.0":
        raise RuntimeError("Generation requires Python Unicode15.0.0")
    lowercase, ignored, cased = [], [], []
    for value in range(0x110000):
        if 0xD800 <= value <= 0xDFFF:
            continue
        text = chr(value)
        lowered = text.lower()
        if lowered != text:
            lowercase.append((value, lowered))
        followed = ("A\u03a3" + text + "A").lower()[1]
        terminal = ("A\u03a3" + text).lower()[1]
        if followed == "\u03c3" and terminal == "\u03c2":
            ignored.append(value)
        elif followed == "\u03c3" and terminal == "\u03c3":
            cased.append(value)
    lines = [
        "// Code generated by tools/reference/generate_host_unicode.py; DO NOT EDIT.",
        "// Source: Python Unicode15.0.0 str.lower, "
        "including unbounded final sigma context.",
        "",
        "package bridge",
        "",
        "var hostLowercase = map[rune]string{",
    ]
    lines.extend(
        f"0x{value:x}: {json.dumps(text, ensure_ascii=False)},"
        for value, text in lowercase
    )
    lines.extend(["}", ""])
    for name, values in [("hostCaseIgnored", ignored), ("hostCased", cased)]:
        lines.append(f"var {name} = [...]hostRuneRange{{")
        lines.extend(
            f"{{first: 0x{start:x}, last: 0x{end:x}}}," for start, end in ranges(values)
        )
        lines.extend(["}", ""])
    root = Path(__file__).resolve().parents[2]
    target = root / "pkg/dependencies/bridge/host_unicode.gen.go"
    formatted = subprocess.run(
        ["gofmt"],
        input="\n".join(lines),
        text=True,
        encoding="utf-8",
        capture_output=True,
        check=True,
    ).stdout.replace("\r\n", "\n")
    manifest = {
        "unicodeVersion": "15.0.0",
        "generator": "tools/reference/generate_host_unicode.py",
        "source": "Python Unicode15.0.0 str.lower",
        "lowercaseMappings": len(lowercase),
        "caseIgnorableRanges": len(ranges(ignored)),
        "casedRanges": len(ranges(cased)),
        "generatedFile": "pkg/dependencies/bridge/host_unicode.gen.go",
        "sha256": hashlib.sha256(formatted.encode("utf-8")).hexdigest(),
    }
    profile = root / "api/dependency-profiles/bridge-host-unicode.json"
    profile.parent.mkdir(parents=True, exist_ok=True)
    profile_text = json.dumps(manifest, indent=2) + "\n"
    if arguments.check:
        if (
            target.read_text(encoding="utf-8") != formatted
            or profile.read_text(encoding="utf-8") != profile_text
        ):
            raise RuntimeError("Source Unicode hostname generation drift")
    else:
        target.write_text(formatted, encoding="utf-8")
        profile.write_text(profile_text, encoding="utf-8")


if __name__ == "__main__":
    main()
